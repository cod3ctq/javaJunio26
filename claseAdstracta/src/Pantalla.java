public class Pantalla {
    int hz ;
    String resoluciom;
    String tipoDePanel;
    String tipoCertificacioM;
    double tamaño;
    int pp1;


    public int getHz() {
        return hz;
    }

    public void setHz(int hz) {
        this.hz = hz;
    }

    public String getResoluciom() {
        return resoluciom;
    }

    public void setResoluciom(String resoluciom) {
        this.resoluciom = resoluciom;
    }

    public String getTipoDePanel() {
        return tipoDePanel;
    }

    public void setTipoDePanel(String tipoDePanel) {
        this.tipoDePanel = tipoDePanel;
    }

    public String getTipoCertificacioM() {
        return tipoCertificacioM;
    }

    public void setTipoCertificacioM(String tipoCertificacioM) {
        this.tipoCertificacioM = tipoCertificacioM;
    }

    public double getTamaño() {
        return tamaño;
    }

    public void setTamaño(double tamaño) {
        this.tamaño = tamaño;
    }

    public int getPp1() {
        return pp1;
    }

    public void setPp1(int pp1) {
        this.pp1 = pp1;
    }
}
